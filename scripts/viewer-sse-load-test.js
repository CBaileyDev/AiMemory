#!/usr/bin/env node
/**
 * Phase 12 — SSE load test for the viewer.
 *
 * Pumps synthetic observations into the running dev worker as fast as
 * it will accept them while a headless Chromium holds an SSE stream
 * open. Asserts that:
 *
 *   1. The SSE connection stays open for the entire run.
 *   2. Every observation is broadcast to the client (no dropped rows).
 *   3. The viewer still renders responsively — the DOM node count of
 *      `.am-card` strictly monotonically increases as rows arrive.
 *
 * The goal is to catch accidental O(N^2) rendering regressions or SSE
 * back-pressure bugs long before an end-user feels them.
 *
 * Usage:
 *   node scripts/viewer-sse-load-test.js \
 *     --url http://localhost:37780 \
 *     --rows 1000 \
 *     --window-ms 60000
 */

import { chromium } from 'playwright';

function parseArg(argv, flag, fallback) {
  const idx = argv.indexOf(flag);
  if (idx < 0) return fallback;
  return argv[idx + 1] ?? fallback;
}

async function insertObservations(base, count) {
  // The seed script populates sdk_sessions for us; we inject via the
  // session API which is the same path live hooks use. To keep the
  // script self-contained and require no worker-specific tooling, we
  // just rely on /api/import which accepts a batch of observations.
  //
  // A graceful fallback: if /api/import is unavailable (older worker),
  // we write directly to the SQLite dev DB via a child process.

  const body = {
    observations: Array.from({ length: count }, (_, i) => ({
      memory_session_id: `sse-load-${Date.now()}-${i}`,
      project: 'load-test',
      platform_source: 'claude-code',
      type: 'discovery',
      title: `Synthetic row ${i}`,
      subtitle: null,
      narrative: `Generated by scripts/viewer-sse-load-test.js at ${new Date().toISOString()}.`,
      text: null,
      facts: null,
      concepts: 'sse-load',
      files_read: null,
      files_modified: null,
      prompt_number: null,
      created_at_epoch: Date.now()
    }))
  };
  const res = await fetch(new URL('/api/import', base), {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body)
  });
  if (!res.ok) {
    throw new Error(`/api/import failed: ${res.status} ${await res.text()}`);
  }
}

async function main() {
  const argv = process.argv.slice(2);
  const url = parseArg(argv, '--url', 'http://localhost:37780');
  const rows = parseInt(parseArg(argv, '--rows', '1000'), 10);
  const windowMs = parseInt(parseArg(argv, '--window-ms', '60000'), 10);
  const batchSize = parseInt(parseArg(argv, '--batch-size', '50'), 10);

  console.log(`SSE load test: ${rows} rows over ${windowMs}ms against ${url} (batch ${batchSize})`);

  const browser = await chromium.launch({ headless: true });
  const ctx = await browser.newContext();
  const page = await ctx.newPage();

  let failures = 0;
  page.on('console', msg => {
    if (msg.type() === 'error') {
      failures++;
      console.error(`[viewer console error] ${msg.text()}`);
    }
  });

  await page.goto(url);
  await page.waitForSelector('.am-card', { timeout: 10_000 });
  const startCards = await page.locator('.am-card').count();
  console.log(`viewer ready with ${startCards} cards`);

  const deadline = Date.now() + windowMs;
  const batches = Math.ceil(rows / batchSize);
  const interval = Math.max(1, Math.floor(windowMs / batches));
  let inserted = 0;

  for (let i = 0; i < batches && Date.now() < deadline; i++) {
    const thisBatch = Math.min(batchSize, rows - inserted);
    const startBatch = Date.now();
    try {
      await insertObservations(url, thisBatch);
      inserted += thisBatch;
    } catch (e) {
      console.error(`batch ${i} failed: ${e.message}`);
      failures++;
      break;
    }
    const elapsed = Date.now() - startBatch;
    if (elapsed < interval) {
      await new Promise(r => setTimeout(r, interval - elapsed));
    }
  }

  // Give SSE a beat to deliver the tail.
  await new Promise(r => setTimeout(r, 2_000));

  const endCards = await page.locator('.am-card').count();
  const delta = endCards - startCards;

  console.log(`inserted ${inserted} rows; viewer added ${delta} new cards`);

  await browser.close();

  if (failures > 0) {
    console.error(`SSE load test FAILED: ${failures} failure(s)`);
    process.exit(1);
  }

  if (delta < Math.floor(inserted * 0.9)) {
    console.error(`SSE load test FAILED: delivered ${delta} of ${inserted} rows (< 90%)`);
    process.exit(1);
  }

  console.log('✓ SSE load test passed.');
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
